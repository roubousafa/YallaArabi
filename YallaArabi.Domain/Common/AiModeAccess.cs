namespace YallaArabi.Domain.Common;

// Who may run new AI Mode generations; the admin switches this from the dashboard.
public static class AiModeAccess
{
    public const string AllStudents = "all";
    public const string SubscribersOnly = "subscribers";
    public const string Disabled = "disabled";

    public static IReadOnlyList<string> All { get; } = new[] { AllStudents, SubscribersOnly, Disabled };

    public static bool IsSupported(string? value) =>
        !string.IsNullOrWhiteSpace(value) && All.Contains(value.Trim().ToLowerInvariant());
}

public static class AiEntryStatuses
{
    // Generated by the AI and shown to students, not reviewed yet.
    public const string Generated = "generated";

    // Reviewed and approved (possibly edited) by an admin.
    public const string Approved = "approved";

    // Hidden from students by an admin.
    public const string Rejected = "rejected";

    // The AI could not understand the query or refused it; cached so it isn't retried.
    public const string Invalid = "invalid";
}

public static class AiImageSources
{
    // Uploaded by an admin and stored on our own file storage.
    public const string Admin = "admin";

    // A free stock photo linked from Pexels, shown with the photographer credit.
    public const string Pexels = "pexels";
}
